-- ===========================================================================
-- Day 22 · PATCH / DELETE 的 select 前后对比验证
-- ---------------------------------------------------------------------------
-- 用法：每条单独粘进 CloudBase 控制台 PostgreSQL 的 SQL 执行窗口。
--
-- 【为什么必须是 select 对比，而不是只看接口返回】
--   接口返回的 JSON 是云函数**以为自己写进去了**的东西。
--   select 查到的是数据库**真的存了什么**。
--   两者不一致时，select 是对的 —— 所以判据要落在 select 上。
--
-- 【为什么每条都带 id LIKE 'd22-%' 过滤】
--   items 里混着6 条seed 和 3 条演示数据，行数会漂。
--   固定用 d22- 前缀的测试 id，验证前后都对得上，不会跟真实数据混淆。
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- 【第1 步】建一条待验证的记录，并把它的「改之前」原样记下来
-- ---------------------------------------------------------------------------
-- 期望：插入成功，1 行。

INSERT INTO items (id, title, plan_date, done, created_at, done_at)
VALUES ('d22-demo', 'D22 验证条目', '2026-10-08', 0,
        '2026-10-08T03:00:00.000Z', NULL);


-- ↓↓↓ 下面这条就是「改之前」的样子，粘下来存着，等下跟改之后的对比 ↓↓↓

-- 【第 1 步· 改之前的快照】
-- 期望：1 行，title = 'D22 验证条目'，done = 0，done_at = NULL
SELECT id, title, plan_date, done, created_at, done_at
FROM items
WHERE id = 'd22-demo';


-- ---------------------------------------------------------------------------
-- 【第 2 步】用 PATCH 改这一条（改 title + 勾上完成）
-- ---------------------------------------------------------------------------
-- ⚠️ 这一步**不要在 SQL 窗口里跑** —— 它是接口做的事。
--    在控制台的「HTTP 访问服务」里对/api/items/d22-demo 发PATCH，
--    body 写：{"title":"D22 验证条目（已改）","done":1}
--
-- 期望响应 200，且 data 里的 title 是新值、done = 1、done_at 有了值。


-- ---------------------------------------------------------------------------
-- 【第 3 步】改之后的 select —— 和第 1 步那条并排比
-- ---------------------------------------------------------------------------
-- 期望：还是 1 行，对比第 1 步的快照：
--   title   : 'D22 验证条目'→ 'D22 验证条目（已改）'   ★ 变了
--   done    : 0 → 1                                   ★ 变了
--   done_at : NULL → '2026-10-08T...'（后端自动补的）  ★ 变了
--   id      : 不变                                     ✔ 没被改
--   created_at : 不变                                  ★ ★ 关键：不该被这次更新动
--
-- created_at 不变这条最容易漏 —— 如果它变了，说明这次「改」实际上做的是
-- 「重新插了一行」，而不是「更新原来那行」。那会造成老数据静默丢失。

SELECT id, title, plan_date, done, created_at, done_at
FROM items
WHERE id = 'd22-demo';


-- ---------------------------------------------------------------------------
-- 【第 4 步】只改一个字段，其余字段必须纹丝不动
-- ---------------------------------------------------------------------------
-- 对d22-demo 发 PATCH，body 只写 {"title":"D22 只改标题"}
--
-- 然后跑这条：

-- 期望：title 变了，plan_date / done / done_at / created_at 全都没变
--（证明 PATCH 是「局部更新」—— body 里没出现的列保持原值）
SELECT id, title, plan_date, done, created_at, done_at
FROM items
WHERE id = 'd22-demo';


-- ---------------------------------------------------------------------------
-- 【第 5 步】DELETE 之前的行数
-- ---------------------------------------------------------------------------
-- 期望：1行（这就是待会儿 DELETE 的目标）

SELECT COUNT(*) AS before_cnt
FROM items
WHERE id = 'd22-demo';


-- ---------------------------------------------------------------------------
-- 【第 6 步】用 DELETE 删这一条
-- ---------------------------------------------------------------------------
-- ⚠️ 同样不要在 SQL 窗口跑 —— 对 /api/items/d22-demo 发 DELETE。
--
-- 期望响应 200，且 data 里回读的就是刚才那条删掉的记录。
--   （回读是故意的：唯一能证明「删对了」的东西，就是被删掉的那行长什么样。）


-- ---------------------------------------------------------------------------
-- 【第 7 步】DELETE 之后的 select —— ★ 今天最关键的一条
-- ---------------------------------------------------------------------------
-- 期望：**0 行**
--
-- 这就是「DELETE 后 GET 不再返回」的数据库侧证据。
-- 如果这里还是 1 行，说明接口返回的200 是在撒谎 —— 而谎报比报错危险得多，
-- 因为报错会让人去查，谎报只会让人接着往下走。

SELECT COUNT(*) AS after_cnt
FROM items
WHERE id = 'd22-demo';


-- ---------------------------------------------------------------------------
-- 【第 8 步】重复删同一条
-- ---------------------------------------------------------------------------
-- 对 /api/items/d22-demo 再发一次 DELETE。
--
-- 期望：**404 NOT_FOUND**（不是 200）
--
-- 这条是今天「删除为什么比新增更容易出事」的直接证明：
--   POST 重复发→ 撞主键 → 409，两发请求天然分开，不会静默；
--   DELETE 重复发 → 第二次「成功地什么都没做」。
-- 如果这里返回 200，调用方会以为「我删成功了」，
-- 而真实情况可能是第一次请求压根没生效 —— 数据还在，却以为已清掉。
--
-- 想让重复删返回 200 的场景，显式带 ?force=1（幂等删除）。


-- ---------------------------------------------------------------------------
-- 【第 9 步】清理：把测试数据删掉，别留在正式库里
-- ---------------------------------------------------------------------------
-- 期望：返回 DELETE 1

DELETE FROM items WHERE id = 'd22-demo';


-- ---------------------------------------------------------------------------
-- 【第 10 步】★ 级联删除的取证 —— 删一条带提醒的清单会连带删掉提醒
-- ---------------------------------------------------------------------------
-- 这是删除比新增更容易出事的第二个原因：范围容易失控。
--
-- 先看这条 d22-demo-cascade 挂着几个提醒：

SELECT r.id, r.item_id, r.title
FROM reminders r
JOIN items i ON r.item_id = i.id
WHERE i.id = 'd22-demo-cascade';

-- 期望：能看到挂在它下面的提醒（0 条或几条都算正常，取决于 seed）
--
-- 然后对 /api/items/d22-demo-cascade 发 DELETE，再跑上面这条：
--
-- ★ 期望：**0 行** —— 提醒跟着清单一起没了
--
-- 这就是 ON DELETE CASCADE 的含义：删一条清单，
-- 挂在它下面的提醒**不会被问一句**就一起删掉。
-- 所以删除前必须先查清楚「这条下面挂着什么」——
-- 只删了「我看见的那一条」，实际影响范围可能是好几条。


-- ===========================================================================
-- 一句话判据
-- ---------------------------------------------------------------------------
-- PATCH：改完之后，select 里**该变的变了、没让变的没变**（尤其 created_at）。
-- DELETE：删完之后，select 返回 **0 行**；再删一次返回 **404**。
-- 只有这两条都成立，才叫「删删改查闭环了」。
-- ===========================================================================